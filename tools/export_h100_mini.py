"""Build tests/data/h100_mini/jobs.json: the H100 PCIe live calls replayed by CI (tests/test_h100_mini.py).

Every job is a live torch._scaled_mm call of the H100 probe (docs/validation_logs/2026-10-15/h100-probe,
results/live_jobs.tar.gz) that mmaemu's replay reproduced (results/analysis/mmaemu_replay.json, which must PASS). A job
is its spec (shape, formats, output dtype, fast/slow, data kind and seed: the inputs are regenerated by
tools/record/live.py, integer hashing, device independent; scales), the logged split (numSplitsK, customOption, the
scheme from the table's rule, workspace) and the expected result: the sha256 of the H100's full output bits, or the
error class for a call the H100 rejected. No output bits are stored.

Selection (smallest M*N*K first, ties by id):
  split     every replayed (fast, S, out dtype, fmt pair) combination, and every customOption with S > 1;
  unsplit   every (fast, out dtype, fmt pair), every workspace and every data kind; every K < 128 (small K);
  rejected  e4m3 x e4m3 -> e5m2, fast and slow.
Only jobs of at most --job-gmac (default 1) GMAC are considered: a combination whose live calls are all larger is not
in the subset (the full replay covers it). The exporter fails above --budget-gmac (default 16) GMAC in total.

usage: PYTHONDONTWRITEBYTECODE=1 python tools/export_h100_mini.py [--check]"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

sys.dont_write_bytecode = True
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import replay_h100_log as R  # noqa: E402

OUT = R.REPO / "tests" / "data" / "h100_mini" / "jobs.json"
FORMAT = "mmaemu-h100-mini/1"
SPEC = ("id", "M", "N", "K", "fa", "fb", "out", "fast", "data", "scale_a", "scale_b", "scale_result")


def build(budget_gmac: float, job_gmac: float) -> dict:
    rep = json.loads(R.OUT.read_text())
    assert rep["format"] == R.FORMAT and rep["summary"]["PASS"], "the replay report must exist and PASS"
    verdict = {j["id"]: j for j in rep["live"]}
    specs = {j["id"]: (src, j) for src, j, _r, _r2, _u in R.live_jobs()}
    ok = [v for v in verdict.values() if v["verdict"] in ("equal", "rejected_as_hardware")
          and v["M"] * v["N"] * v["K"] <= job_gmac * 1e9]
    ok.sort(key=lambda v: (v["M"] * v["N"] * v["K"], v["id"]))
    chosen: dict = {}

    def take(group: str, key, pred):
        v = next((v for v in ok if pred(v)), None)        # the group's smallest job
        if v is not None:
            chosen.setdefault(v["id"], f"{group} {key}")

    split = [v for v in ok if v["verdict"] == "equal" and v["S"] > 1]
    unsplit = [v for v in ok if v["verdict"] == "equal" and v["S"] == 1]
    for k in sorted({(v["fast"], v["S"], v["out"], v["fa"], v["fb"]) for v in split}):
        take("split", k, lambda v, k=k: v["verdict"] == "equal" and (v["fast"], v["S"], v["out"], v["fa"], v["fb"]) == k)
    for ws in sorted({v["ws"] for v in split}):
        take("split workspace", ws, lambda v, ws=ws: v["verdict"] == "equal" and v["S"] > 1 and v["ws"] == ws)
    for c in sorted({v["custom"] for v in split}):
        take("split customOption", c, lambda v, c=c: v["verdict"] == "equal" and v["S"] > 1 and v["custom"] == c)
    for k in sorted({(v["fast"], v["out"], v["fa"], v["fb"]) for v in unsplit}):
        take("unsplit", k, lambda v, k=k: v["verdict"] == "equal" and v["S"] == 1 and
             (v["fast"], v["out"], v["fa"], v["fb"]) == k)
    for ws in sorted({v["ws"] for v in unsplit}):
        take("unsplit workspace", ws, lambda v, ws=ws: v["verdict"] == "equal" and v["S"] == 1 and v["ws"] == ws)
    for kind in sorted({specs[v["id"]][1]["data"]["kind"] for v in unsplit}):
        take("unsplit data", kind, lambda v, kind=kind: v["verdict"] == "equal" and v["S"] == 1 and
             specs[v["id"]][1]["data"]["kind"] == kind)
    for k in sorted({(v["K"], v["fast"]) for v in unsplit if v["K"] < 128}):
        take("small K", k, lambda v, k=k: v["verdict"] == "equal" and (v["K"], v["fast"]) == k)
    for fast in (True, False):
        take("rejected", fast, lambda v, fast=fast: v["verdict"] == "rejected_as_hardware" and v["fast"] == fast)
    jobs = []
    for jid in sorted(chosen):
        v, (src, spec) = verdict[jid], specs[jid]
        e = {k: spec.get(k) for k in SPEC}
        e.update(src=src, ws=v["ws"], why=chosen[jid])
        if v["verdict"] == "equal":
            e.update(S=v["S"], custom=v["custom"], scheme=v["scheme"], expect={"sha256": _sha(jid)})
        else:
            e.update(S=None, expect={"error": "ReferenceRejectsError"})
        jobs.append(e)
    gmac = sum(j["M"] * j["N"] * j["K"] for j in jobs) / 1e9
    assert gmac <= budget_gmac, f"{gmac:.1f} GMAC > budget {budget_gmac}"
    return {"format": FORMAT, "log": R.LOG.relative_to(R.REPO).as_posix(),
            "replay_sha256": hashlib.sha256(R.OUT.read_bytes()).hexdigest(),
            "live_jobs_sha256": hashlib.sha256(R.LIVE.read_bytes()).hexdigest(),
            "job_gmac_cap": job_gmac, "n_jobs": len(jobs), "gmac": round(gmac, 3), "jobs": jobs}


_SHA: dict = {}


def _sha(jid: str) -> str:
    if not _SHA:
        for _s, j, r, _r2, _u in R.live_jobs():
            if r is not None and not r.get("error"):
                _SHA[j["id"]] = r["full_sha256"]
    return _SHA[jid]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--budget-gmac", type=float, default=16.0)
    ap.add_argument("--job-gmac", type=float, default=1.0, help="largest job considered (GMAC)")
    a = ap.parse_args()
    data = (json.dumps(build(a.budget_gmac, a.job_gmac), indent=1, sort_keys=True) + "\n").encode()
    if a.check:
        same = OUT.exists() and OUT.read_bytes() == data
        print("check:", "OK" if same else "DIFFERS")
        sys.exit(0 if same else 1)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(data)
    d = json.loads(data)
    print(f"wrote {OUT} ({len(data)} bytes): {d['n_jobs']} jobs, {d['gmac']} GMAC")


if __name__ == "__main__":
    main()
