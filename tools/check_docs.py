class Result:
    def __init__(self) -> None:
        self.errors: list[str] = []
        self.notes: list[str] = []

    def error(self, where: str, msg: str) -> None:
        self.errors.append(f"{where}: {msg}")

    def note(self, msg: str) -> None:
        self.notes.append(msg)


# ------------------------------------------------------------------------------------------------ helpers
def rel(p: Path) -> str:
    try:
        return p.relative_to(ROOT).as_posix()
    except ValueError:
        return str(p)


def doc_files() -> list[Path]:
    files = [p for p in (README, ROOT / "CHANGELOG.md", ROOT / "llms.txt") if p.is_file()]
    docs = ROOT / "docs"
    if docs.is_dir():
        for p in sorted(docs.rglob("*")):
            r = rel(p)
            if p.is_file() and (r.endswith(".md") or r.endswith(".md.txt")) and not r.startswith(EXCLUDE_DIRS):
                files.append(p)
    return files


def code_files() -> list[Path]:
    pkg = ROOT / "mmaemu"
    return sorted(p for p in pkg.rglob("*") if p.is_file() and p.suffix in (".py", ".cu", ".cuh")
                  and "__pycache__" not in p.parts)


def strip_code_fences(lines: list[str]) -> list[tuple[int, str, bool]]:
    """(line number, text, inside a fenced code block)."""
    out, fence = [], False
    for i, line in enumerate(lines, 1):
        if line.lstrip().startswith("```"):
            out.append((i, line, True))
            fence = not fence
            continue
        out.append((i, line, fence))
    return out


def repo_files() -> set[str]:
    """Files a reference may point to: the git-tracked files (staged ones included) in a git checkout, so that an
    untracked local file does not satisfy a reference; otherwise every file of the tree."""
    if (ROOT / ".git").exists():
        try:
            listed = subprocess.run(["git", "-C", str(ROOT), "ls-files", "-z"], check=True,
                                    capture_output=True).stdout.decode().split("\0")
            return {f for f in listed if f and (ROOT / f).is_file()}
        except (OSError, subprocess.CalledProcessError):
            pass
    out = set()
    for p in ROOT.rglob("*"):
        r = rel(p)
        if p.is_file() and not r.startswith((".git/", "build/", "dist/")) and "__pycache__" not in p.parts:
            out.add(r)
    return out


