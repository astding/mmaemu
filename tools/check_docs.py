def live_truth(truth_dir: Path | None) -> tuple[str, dict] | None:
    if truth_dir is None:
        return None
    man = truth_dir / "manifest.json"
    raw = man.read_bytes()
    m = json.loads(raw)
    recs = {}
    for r in m["recordings"]:
        s = r.get("stats", {})
        recs[r["id"]] = (r["kind"], r["level"], s.get("n_outputs", 0), s.get("n_output_values", 0))
    return hashlib.sha256(raw).hexdigest(), recs


def check_truth_snapshot(res: Result, truth_dir: Path | None) -> None:
    live = live_truth(truth_dir)
    if live is None:
        res.note(f"truth ids resolved against the pinned snapshot ({len(TRUTH_RECORDINGS)} recordings, manifest "
                 f"sha256 {TRUTH_MANIFEST_SHA256[:16]}...); set MMAEMU_TRUTH_DIR to cross-check the live manifest")
        return
    sha, recs = live
    if sha != TRUTH_MANIFEST_SHA256 or recs != TRUTH_RECORDINGS:
        res.error("tools/check_docs.py", f"truth snapshot differs from {truth_dir}/manifest.json (sha256 {sha[:16]}..."
                  " vs pinned); regenerate with --print-truth-snapshot")
    else:
        res.note(f"truth snapshot == live manifest {truth_dir}/manifest.json (sha256 {sha[:16]}...)")


def resolve_truth(pattern: str) -> list[str]:
    if any(ch in pattern for ch in "*?["):
        return [i for i in TRUTH_RECORDINGS if fnmatch.fnmatchcase(i, pattern)]
    return [pattern] if pattern in TRUTH_RECORDINGS else []


def inventory_table() -> str:
    groups: dict[str, list] = defaultdict(lambda: [0, 0, 0, set(), set()])
    for rid, (kind, level, n_out, n_val) in TRUTH_RECORDINGS.items():
        g = groups[rid.split(".", 1)[0]]
        g[0] += 1
        g[1] += n_out
        g[2] += n_val
        g[3].add(kind)
        g[4].add(level.split(" (")[0])
    lines = ["| Group | Kinds | Levels | Recordings | Recorded outputs | Output values | Evidence |",
             "|---|---|---|---:|---:|---:|---|"]
    tot = [0, 0, 0]
    for name in sorted(groups):
        n, o, v, kinds, levels = groups[name]
        tot = [tot[0] + n, tot[1] + o, tot[2] + v]
        lines.append(f"| {name} | {', '.join(sorted(kinds))} | {', '.join(sorted(levels))} | {n} | {o:,} | {v:,} | "
                     f"`truth:{name}.*` |")
    lines.append(f"| all | | | {tot[0]} | {tot[1]:,} | {tot[2]:,} | `truth:*` |")
    return "\n".join(lines)


# ------------------------------------------------------------------------------------------------ checks
def check_forbidden(res: Result, files: list[Path]) -> int:
    allowed = 0
    for p in files:
        text = p.read_text(errors="replace")
        for i, line in enumerate(text.splitlines(), 1):
            allow = set(ALLOW_RE.findall(line))
            for rid, rx, msg in FORBIDDEN_RE:
                if rx.search(line):
                    if rid in allow:
                        allowed += 1
                    else:
                        res.error(f"{rel(p)}:{i}", f"forbidden wording [{rid}] {msg}: {line.strip()[:120]!r}")
        # unscoped "bit-identical to torch._scaled_mm": per sentence (paragraphs joined)
        for para in re.split(r"\n\s*\n", text):
            flat = " ".join(para.split())
            for sent in re.split(r"(?<=[.!?])\s+(?=[A-Z(`*])", flat):
                if (re.search(BITID, sent, re.I) and re.search(SCALED_MM, sent)
                        and not SCOPE_TOKENS.search(sent) and "allow unscoped-bitid" not in sent):
                    res.error(rel(p), f"forbidden wording [unscoped-bitid] a bitwise claim about torch._scaled_mm "
                              f"without its scope (GPU/profile): {sent[:160]!r}")
    return allowed


def check_refs(res: Result, files: list[Path], files_in_repo: set[str]) -> int:
    n = 0
    for p in files:
        for i, line in enumerate(p.read_text(errors="replace").splitlines(), 1):
            for kind, target in REF_RE.findall(line):
                n += 1
                where = f"{rel(p)}:{i}"
                if kind == "truth":
                    if not resolve_truth(target):
                        res.error(where, f"truth reference `truth:{target}` matches no recording id")
                elif kind == "repo":
                    hits = [f for f in files_in_repo if fnmatch.fnmatchcase(f, target)] if any(
                        c in target for c in "*?[") else ([target] if target in files_in_repo else [])
                    if not hits:
                        res.error(where, f"repo reference `repo:{target}` does not exist")
                elif kind == "log":
                    if not target.startswith(("docs/validation_logs/", "docs/release_logs/")):
                        res.error(where, f"log reference `log:{target}` must point into docs/validation_logs/ or "
                                  "docs/release_logs/")
                    elif target not in files_in_repo:
                        res.error(where, f"log reference `log:{target}` does not exist")
    return n


def check_validation_numbers(res: Result) -> None:
    if not VALIDATION.is_file():
        res.error("docs/validation.md", "missing")
        return
    lines = VALIDATION.read_text().splitlines()
    in_comment = False
    for i, line, fence in strip_code_fences(lines):
        s = line.strip()
        if fence or not s or s.startswith("#") or re.fullmatch(r"\|?[\s:|-]+\|?", s):
            continue
        if s.startswith("<!--"):
            in_comment = not s.endswith("-->")
            continue
        if in_comment:
            in_comment = not s.endswith("-->")
            continue
        body = REF_RE.sub("", s)
        body = re.sub(r"\]\([^)]*\)", "]", body)  # link targets
        if NUMBER_RE.search(body) and not REF_RE.search(s):
            res.error(f"docs/validation.md:{i}", f"states a number without an evidence reference: {s[:120]!r}")


def check_inventory(res: Result, fix: bool) -> None:
    if not VALIDATION.is_file():
        return
    text = VALIDATION.read_text()
    want = f"{INVENTORY_BEGIN}\n{inventory_table()}\n{INVENTORY_END}"
    m = re.search(re.escape(INVENTORY_BEGIN) + r".*?" + re.escape(INVENTORY_END), text, re.S)
    if not m:
        res.error("docs/validation.md", "generated truth inventory block missing (markers)")
        return
    if m.group(0) != want:
        if fix:
            VALIDATION.write_text(text[:m.start()] + want + text[m.end():])
            res.note("docs/validation.md: truth inventory table rewritten")
        else:
            res.error("docs/validation.md", "truth inventory table differs from the truth manifest "
                      "(run python tools/check_docs.py --fix)")


def table_first_cells(lines: list[str], start: int) -> list[str]:
    cells = []
    for line in lines[start:]:
        s = line.strip()
        if s.startswith("#"):
            break
        if s.startswith("|"):
            first = s.strip("|").split("|")[0]
            first = re.sub(r"[*`_]", "", first).strip()
            if first and not re.fullmatch(r":?-+:?", first):
                cells.append(first)
    return cells


def check_scope_rows(res: Result) -> None:
    if not VALIDATION.is_file():
        return
    lines = VALIDATION.read_text().splitlines()
    heads = [i for i, line in enumerate(lines) if re.match(r"#+\s+Scope\b", line)]
    if not heads:
        res.error("docs/validation.md", "no scope table under a 'Scope' heading")
        return
    cells = {c.lower() for h in heads for c in table_first_cells(lines, h + 1)}
    for want in AUDIT_SCOPE_ROWS:
        if want.replace("_", "").lower() not in {c.replace("_", "") for c in cells}:
            res.error("docs/validation.md", f"scope row missing: {want!r}")


def check_readme(res: Result) -> None:
    if not README.is_file():
        res.error("README.md", "missing")
        return
    text = README.read_text()
    paras = [" ".join(p.split()) for p in re.split(r"\n\s*\n|\n(?=\s*[-*|] )", text)]
    if not any("`hopper`" in p and "experimental" in p for p in paras):
        res.error("README.md", "must mark the `hopper` preset experimental (same paragraph/item)")
    if not any("`b200_mma_sync`" in p and "`blackwell`" in p and "experimental" in p for p in paras):
        res.error("README.md", "must mark `b200_mma_sync` (alias `blackwell`) experimental (same paragraph/item)")
    if not any(re.search(r"sm_120[^.]*\bnot\s+(modell?ed|a\s+model)", p) for p in paras):
        res.error("README.md", "must state that sm_120 is not modelled")


def check_links(res: Result, files: list[Path], files_in_repo: set[str]) -> int:
    n = 0
    dirs = set()
    for f in files_in_repo:
        d = posixpath.dirname(f)
        while d and d not in dirs:
            dirs.add(d)
            d = posixpath.dirname(d)
    for p in files:
        for i, line in enumerate(p.read_text(errors="replace").splitlines(), 1):
            for target in re.findall(r"\]\(([^)\s]+)\)", line):
                if target.startswith(GITHUB):
                    m = re.match(re.escape(GITHUB) + r"(blob|tree)/master/([^#?]+)", target)
                    if not m:
                        continue
                    path = m.group(2).rstrip("/")
                    ok = path in files_in_repo or path in dirs
                elif re.match(r"[a-z]+:", target) or target.startswith("#"):
                    continue
                else:
                    path = os.path.normpath((p.parent / target.split("#")[0]).as_posix())
                    path = rel(Path(path))
                    ok = path in files_in_repo or path in dirs or (ROOT / path).exists()
                n += 1
                if not ok:
                    res.error(f"{rel(p)}:{i}", f"link target does not exist: {target}")
    return n


# ------------------------------------------------------------------------------------------------ main
def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--scan-code", action="store_true", help="also scan mmaemu/**/*.py, *.cu, *.cuh for forbidden wording")
    ap.add_argument("--fix", action="store_true", help="rewrite the generated truth inventory table")
    ap.add_argument("--truth-dir", type=Path, default=os.environ.get("MMAEMU_TRUTH_DIR") or None,
                    help="hardware ground truth (default $MMAEMU_TRUTH_DIR) for the live cross-check")
    ap.add_argument("--print-truth-snapshot", action="store_true",
                    help="print the snapshot literal for this file from --truth-dir and exit")
    args = ap.parse_args(argv)
    truth_dir = Path(args.truth_dir) if args.truth_dir else None
    if args.print_truth_snapshot:
        if truth_dir is None:
            ap.error("--print-truth-snapshot needs --truth-dir or MMAEMU_TRUTH_DIR")
        sha, recs = live_truth(truth_dir)
        print(f'TRUTH_MANIFEST_SHA256 = "{sha}"')
        print("# id: (kind, level, n_outputs, n_output_values) from the truth manifest stats")
        print("TRUTH_RECORDINGS = {")
        for k, v in recs.items():
            print(f"    {k!r}: {v!r},")
        print("}")
        return 0
    res = Result()
    files = doc_files()
    scan = files + (code_files() if args.scan_code else [])
    in_repo = repo_files()
    check_truth_snapshot(res, truth_dir)
    allowed = check_forbidden(res, scan)
    nrefs = check_refs(res, files, in_repo)
    check_inventory(res, args.fix)
    check_validation_numbers(res)
    check_scope_rows(res)
    check_readme(res)
    nlinks = check_links(res, files, in_repo)
    for n in res.notes:
        print(f"note: {n}")
    print(f"scanned {len(scan)} files ({len(files)} docs{', package code' if args.scan_code else ''}); "
          f"{nrefs} evidence references; {nlinks} links; {allowed} allowed quotations")
    for e in res.errors:
        print(f"ERROR {e}")
    print(f"check_docs: {'FAIL' if res.errors else 'PASS'} ({len(res.errors)} errors)")
    return 1 if res.errors else 0


if __name__ == "__main__":
    sys.exit(main())
